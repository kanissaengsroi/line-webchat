const dicts: Record<Lang, Dict> = { th, en };
export type TKey = keyof Dict;

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = dicts[lang][key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function typeLabel(lang: Lang, type: MessageType) {
  return translate(lang, `type_${type}` as TKey);
}
